"""Generate CREDITS.md from the downloaded image metadata, voice provider and music settings."""
from __future__ import annotations

import json

from .common import IMAGES, ROOT, VOICE, all_video_ids, load_video

# Files whose Commons license claim deserves a manual check before publishing (old photographs
# uploaded as "own work", or missing photographer information).
REVIEW = {
    "Margarita Manso 3V.jpg": "Historic photo uploaded as own work under CC BY-SA 4.0; original photographer not stated.",
    "Rosa Chacel en su juventud.jpg": "Historic photo uploaded as own work under CC BY-SA 4.0; original photographer not stated.",
    "Frankfurterkueche.jpg": "Public-domain claim without a named author or source on Commons.",
    "Haus-Kapaunplatz 10-01.jpg": "Commons says 'Haus Kapaunplatz 10'; it is in Commons' Schütte-Lihotzky category as her 1950-52 kindergarten, but confirm before publishing.",
    "Victoria Kent.png": "Public domain claimed; author listed as 'No consta' (unknown).",
    "Maruja Mallo.JPG": "Tagged PD-AR-Photo (taken from a 1966 Argentine encyclopedia); public domain in Argentina, "
                        "US status may depend on URAA.",
}


def clean_author(a: str) -> str:
    a = (a or "Unknown").replace("Unknown authorUnknown author", "Unknown author")
    a = a.replace("AnonymousUnknown author", "Anonymous").replace("|", "/")
    return a[:80]

VOICES = {
    "gtts": "Google Translate text-to-speech (Spain-Spanish female voice, via the gTTS library). "
            "Not an official Google API; review Google's terms before commercial use.",
    "edge": "Microsoft Edge neural voice es-ES-ElviraNeural (via edge-tts).",
    "piper": "Piper TTS, voice es_ES-sharvard-medium (speaker F), trained on the Sharvard corpus (CC BY 3.0).",
}


def main() -> None:
    out = ["# Credits and licenses", "",
           "Generated by `python -m pipeline.credits` from `assets/images/*/sources.json`. "
           "Images marked **(check)** need a manual license review before publishing (see bottom).", ""]
    for vid in all_video_ids():
        cfg = load_video(vid)
        sources = json.loads((IMAGES / vid / "sources.json").read_text())
        meta = json.loads((VOICE / vid / "sentences.json").read_text())
        music = cfg.get("music", {})
        out += [f"## {cfg['title']} (`{vid}`)", "",
                f"- **Voiceover:** {VOICES.get(meta['provider'], meta['provider'])}",
                f"- **Music:** original procedural composition generated by `pipeline/music.py` "
                f"(style `{music.get('style')}`, {music.get('bpm')} BPM, seed {music.get('seed')}). "
                "No third-party samples; free to use.",
                "", "| # | Image | Author | Date | License | Source |", "|---|---|---|---|---|---|"]
        for k, (title, s) in enumerate(sources.items(), 1):
            flag = " **(check)**" if title in REVIEW else ""
            author = clean_author(s.get("artist"))
            lic = s.get("license") or "?"
            if s.get("license_url"):
                lic = f"[{lic}]({s['license_url']})"
            date = (s.get("date") or "").split("date QS")[0][:30]
            out.append(f"| {k} | {title}{flag} | {author} | {date} | {lic} | [Commons]({s['page']}) |")
        out.append("")
    out += ["## Brand, fonts and tools", "",
            "- Purple Street logo and cat-eye glasses mark: from purplestreet.org (brand owner's own assets).",
            "- Archivo Black (Omnibus-Type) and Inter (Rasmus Andersson): SIL Open Font License 1.1, see `assets/fonts/`.",
            "- Word timing: faster-whisper (MIT), model `small` (OpenAI Whisper weights, MIT).",
            "- Rendering: Pillow, NumPy, FFmpeg.", "",
            "## Licenses that need a manual check", ""]
    for title, why in REVIEW.items():
        out.append(f"- **{title}**: {why}")
    out += ["", "CC BY / CC BY-SA images are credited on screen while they are shown. Add this list (or a link to it) "
            "to the TikTok caption to complete attribution, and note that CC BY-SA requires derivatives of those "
            "specific images to keep the same license."]
    (ROOT / "CREDITS.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    print("  wrote", ROOT / "CREDITS.md")


if __name__ == "__main__":
    main()
